"""
Make a Linux PLC-SDK out of a target sysroot, e.g. the one Yocto's
populate_sdk produces for an image. Standalone, so that image builds can run
it without the rest of Beremiz.

SDK directory content:
    manifest.json       read by SDKManager
    plc_sdk_builder.py  PLCSDKBuilder, used instead of the target builder
    definitions.py      clang flags pointing at the sysroot below
    features.py         IDE's own features, restricted to Linux target
    sysroot/            copy of given sysroot

clang and lld are not part of the SDK, see ToolchainBinary in plc_sdk_builder.py.
"""

import argparse
import glob
import json
import os
import shlex
import shutil
import sys

DEFINITIONS = """\
#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# generated by make_plc_sdk.py
import os

# current file directory, absolute since compiler runs in build directory
plc_sdk_dir = os.path.dirname(os.path.abspath(__file__)).replace('\\\\', '/')

# toolchain shared by all SDKs of a host, in BEREMIZ_APPDATA/toolchains
TOOLCHAIN = {toolchain!r}

# Compile flags
CFLAGS = [
{cflags}]

# Link flags
LDFLAGS = [
{ldflags}]
"""

FEATURES = """\
#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# generated by make_plc_sdk.py

# Same libraries and extensions as the IDE using this SDK, Linux target only
import util.paths as _paths
_features_path = _paths.Bpath("features.py")
exec(compile(open(_features_path).read(), _features_path, "exec"))
targets = ["Linux"]
"""


def FindGCCInstallDir(sysroot):
    """ clang needs gcc's crt*.o and libgcc, wherever the distro put them """
    found = [os.path.dirname(p) for p in
             glob.glob(os.path.join(sysroot, "usr", "lib*", "**", "crtbeginS.o"),
                       recursive=True)]
    if len(found) != 1:
        sys.exit("Expected one crtbeginS.o in sysroot, found %d: %s\n"
                 "Use --gcc-install-dir." % (len(found), found))
    return os.path.relpath(found[0], sysroot)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sysroot", required=True, help="target sysroot to copy in the SDK")
    parser.add_argument("--target", required=True, help="clang target triple, e.g. aarch64-poky-linux")
    parser.add_argument("--name", required=True, help="SDK name shown in SDKManager")
    parser.add_argument("--toolchain", required=True, help="toolchain name, e.g. llvm-21")
    parser.add_argument("--gcc-install-dir", help="relative to sysroot, guessed if omitted")
    parser.add_argument("--cflags", default="", help="target specific compile flags, e.g. --cflags=-mcpu=cortex-a76")
    parser.add_argument("sdkdir", help="SDK directory to create")
    args = parser.parse_args()

    if os.path.exists(args.sdkdir):
        sys.exit("%s already exists" % args.sdkdir)

    gcc_install_dir = args.gcc_install_dir or FindGCCInstallDir(args.sysroot)

    os.makedirs(args.sdkdir)
    shutil.copytree(args.sysroot, os.path.join(args.sdkdir, "sysroot"), symlinks=True)

    shutil.copy(os.path.join(os.path.dirname(os.path.realpath(__file__)), "plc_sdk_builder.py"),
                args.sdkdir)

    # Paths are f-strings relative to plc_sdk_dir, other flags are literals
    common = ['"--target=%s"' % args.target,
              'f"--sysroot={plc_sdk_dir}/sysroot"',
              'f"--gcc-install-dir={plc_sdk_dir}/sysroot/%s"' % gcc_install_dir.replace(os.sep, "/")]
    cflags = common + list(map(repr, shlex.split(args.cflags)))
    ldflags = common + ['"-fuse-ld=lld"']
    with open(os.path.join(args.sdkdir, "definitions.py"), "w") as f:
        f.write(DEFINITIONS.format(
            toolchain=args.toolchain,
            cflags="".join("    %s,\n" % flag for flag in cflags),
            ldflags="".join("    %s,\n" % flag for flag in ldflags)))

    with open(os.path.join(args.sdkdir, "features.py"), "w") as f:
        f.write(FEATURES)

    with open(os.path.join(args.sdkdir, "manifest.json"), "w") as f:
        json.dump({"name": args.name,
                   "target": "Linux",
                   "triple": args.target,
                   "toolchain": args.toolchain}, f, indent=4)


if __name__ == "__main__":
    main()
