# Copied into a Linux PLC-SDK by make_plc_sdk.py.
# SetSDKPath put the SDK directory first in sys.path, hence the bare names.

import os
import shlex

from definitions import plc_sdk_dir, TOOLCHAIN, CFLAGS, LDFLAGS

from targets.Linux.Linux_target import Linux_target
import util.paths as paths


def ToolchainBinary(name):
    """
    clang and lld come from a toolchain shared by all SDKs of a host, unless
    the SDK bundles its own. Falls back to PATH when neither is installed.
    """
    for toolchain_dir in (os.path.join(plc_sdk_dir, "toolchain"),
                          paths.AppDataPath("toolchains", TOOLCHAIN)):
        if os.path.isdir(toolchain_dir):
            return os.path.join(toolchain_dir, "bin", name)
    return name


class PLCSDKBuilder(Linux_target):
    """
    Native Linux build, cross compiled with clang against the SDK's sysroot.

    Only toolchain and sysroot come from the SDK: target code (plc_Linux_main.c)
    and extensions' C code are generated by the IDE as for a native build, so
    IDE and target runtime must be the same Beremiz version.
    """

    def getBuilderCFLAGS(self):
        # toolchain_gcc joins and shlex.splits these, SDK path may hold spaces
        return Linux_target.getBuilderCFLAGS(self) + list(map(shlex.quote, CFLAGS))

    def getBuilderLDFLAGS(self):
        return Linux_target.getBuilderLDFLAGS(self) + list(map(shlex.quote, LDFLAGS))

    def getCompiler(self):
        return ToolchainBinary("clang")

    def getLinker(self):
        return ToolchainBinary("clang")

    def GetTargetName(self):
        return "Linux"
